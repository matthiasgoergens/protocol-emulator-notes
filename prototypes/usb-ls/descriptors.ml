(* Descriptors of a low-speed HID boot keyboard. Data shared by the hardened engine's ROM, the
   firmware's controller and the reference device model: it is the device's specification, not
   logic. VID 0x1209 / PID 0x0001 is pid.codes' test pair. *)

let device =
  [ 0x12; 0x01; 0x10; 0x01;       (* bLength, DEVICE, bcdUSB 1.10 *)
    0x00; 0x00; 0x00; 0x08;       (* class per interface; bMaxPacketSize0 8 (low speed) *)
    0x09; 0x12; 0x01; 0x00;       (* idVendor 0x1209, idProduct 0x0001 *)
    0x00; 0x01; 0x00; 0x00; 0x00; 0x01 ]  (* bcdDevice 1.00, no strings, 1 configuration *)

let report =
  (* the boot keyboard report descriptor from HID 1.11, appendix B.1 *)
  [ 0x05; 0x01; 0x09; 0x06; 0xA1; 0x01; 0x05; 0x07; 0x19; 0xE0; 0x29; 0xE7; 0x15; 0x00; 0x25; 0x01;
    0x75; 0x01; 0x95; 0x08; 0x81; 0x02; 0x95; 0x01; 0x75; 0x08; 0x81; 0x01; 0x95; 0x05; 0x75; 0x01;
    0x05; 0x08; 0x19; 0x01; 0x29; 0x05; 0x91; 0x02; 0x95; 0x01; 0x75; 0x03; 0x91; 0x01; 0x95; 0x06;
    0x75; 0x08; 0x15; 0x00; 0x25; 0x65; 0x05; 0x07; 0x19; 0x00; 0x29; 0x65; 0x81; 0x00; 0xC0 ]

let config =
  [ 0x09; 0x02; 0x22; 0x00; 0x01; 0x01; 0x00; 0xA0; 0x32 ]      (* 34 bytes total, 1 interface, 100 mA *)
  @ [ 0x09; 0x04; 0x00; 0x00; 0x01; 0x03; 0x01; 0x01; 0x00 ]    (* interface: HID, boot, keyboard *)
  @ [ 0x09; 0x21; 0x11; 0x01; 0x00; 0x01; 0x22; List.length report; 0x00 ]  (* HID 1.11 *)
  @ [ 0x07; 0x05; 0x81; 0x03; 0x08; 0x00; 0x0A ]                (* EP1 IN interrupt, 8 bytes, 10 ms *)

let () = assert (List.length config = 0x22)

let rom = device @ config @ report
let dev_base = 0 and cfg_base = List.length device
let rep_base = List.length device + List.length config
