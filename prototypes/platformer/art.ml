(* Original pixel art for the platformer: 16 x 16 background tiles and 16-pixel-wide sprites,
   2 bits per pixel ('.' transparent, '1'-'3' the palette's three colours). Nothing here is
   copied or traced from an existing game. *)

let parse rows =
  Array.of_list (List.map (fun r ->
    if String.length r <> 16 then failwith ("art row not 16 wide: " ^ r);
    Array.init 16 (fun i -> match r.[i] with '1' -> 1 | '2' -> 2 | '3' -> 3 | _ -> 0)) rows)

